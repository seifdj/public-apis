/**
 * Loads French communes into `public.cities` from the official geo API
 * (https://geo.api.gouv.fr), as SQL you then apply with `supabase db query`
 * or psql. No dependency, run with: `node --experimental-strip-types scripts/load-cities.ts > supabase/seed/cities.sql`
 *
* Offline: `CITIES_JSON=path/to/communes.json` reads a saved copy of the same payload.
 *
 * Fields: code INSEE, nom, codeDepartement, codeRegion, codesPostaux, population, centre (GeoJSON point).
 */
const API = 'https://geo.api.gouv.fr/communes?fields=code,nom,codeDepartement,codeRegion,codesPostaux,population,centre&format=json';

interface Commune {
  code: string;
  nom: string;
  codeDepartement: string;
  codeRegion?: string;
  codesPostaux?: string[];
  population?: number;
  centre?: { type: 'Point'; coordinates: [number, number] };
}

function slugify(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/œ/g, 'oe') // same result as Postgres unaccent(), used by scripts/load-cities.sql
    .replace(/æ/g, 'ae')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

/** INSEE codes of Corsica use 2A/2B; map them to a numeric id that stays unique. */
function toId(code: string): number {
  return Number(code.replace(/^2A/, '201').replace(/^2B/, '202'));
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

async function main() {
  let communes: Commune[];
  if (process.env.CITIES_JSON) {
    const { readFile } = await import('node:fs/promises');
    communes = JSON.parse(await readFile(process.env.CITIES_JSON, 'utf8')) as Commune[];
  } else {
    const res = await fetch(API);
    if (!res.ok) throw new Error(`geo.api.gouv.fr ${res.status}`);
    communes = (await res.json()) as Commune[];
  }
  const rows = communes
    .filter((c) => c.centre && c.codeDepartement)
    .map((c) => {
      const [lng, lat] = c.centre!.coordinates;
      const postal = `array[${(c.codesPostaux ?? []).map(q).join(',')}]::text[]`;
      return `(${toId(c.code)}, ${q(c.code)}, ${q(c.nom)}, ${q(slugify(c.nom))}, ${q(c.codeDepartement)}, ${c.codeRegion ? q(c.codeRegion) : 'null'}, ${postal}, ${c.population ?? 'null'}, extensions.ST_SetSRID(extensions.ST_MakePoint(${lng}, ${lat}), 4326)::extensions.geography)`;
    });

  process.stdout.write(`-- Generated by scripts/load-cities.ts on ${new Date().toISOString()} (${rows.length} communes)\n`);
  const batch = 500;
  for (let i = 0; i < rows.length; i += batch) {
    process.stdout.write(
      `insert into public.cities (id, insee_code, name, slug, department, region, postal_codes, population, location) values\n${rows.slice(i, i + batch).join(',\n')}\non conflict (id) do update set name = excluded.name, slug = excluded.slug, department = excluded.department, region = excluded.region, postal_codes = excluded.postal_codes, population = excluded.population, location = excluded.location;\n`,
    );
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
