// Builds supabase/seed/demo.sql from shops.json and archetypes.json:
// 30 demo shops and 150 posts in several cities. Usage: node scripts/demo/build-seed-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const shops = JSON.parse(readFileSync(join(here, 'shops.json'), 'utf8'));
const archetypes = JSON.parse(readFileSync(join(here, 'archetypes.json'), 'utf8'));
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a, cast) => `array[${a.map((x) => (typeof x === 'number' ? x : q(x))).join(', ')}]::${cast}`;

const sql = `-- Demo data: ${shops.length} shops, ${shops.reduce((n, s) => n + s.arch.length, 0)} posts. GENERATED by scripts/demo/build-seed-sql.mjs, do not edit.
-- The accounts cannot sign in (no password, no identity, banned). Photos live in the folder of the
-- "demo-assets" account (see scripts/demo/make-demo-images.mjs). Idempotent.
-- Remove everything with:  delete from auth.users where email like 'demo%@bizz.test';
begin;

create temp table _demo_shops (idx int, slug text, name text, owner_name text, bio text, insee text, instagram text, arch int[]) on commit drop;
insert into _demo_shops values
${shops.map((s, i) => `  (${i + 1}, ${q(s.slug)}, ${q(s.name)}, ${q(s.owner)}, ${q(s.bio)}, ${q(s.insee)}, ${q(s.instagram)}, ${arr(s.arch, 'int[]')})`).join(',\n')};

create temp table _demo_arch (id int, cat text, type text, title text, price int, descr text, tags text[]) on commit drop;
insert into _demo_arch values
${archetypes.map((a) => `  (${a.id}, ${q(a.cat)}, ${q(a.type)}, ${q(a.title)}, ${a.price ?? 'null'}, ${q(a.desc)}, ${arr(a.tags, 'text[]')})`).join(',\n')};

do $$ begin
  if (select count(*) from _demo_shops s join public.cities c on c.insee_code = s.insee) <> (select count(*) from _demo_shops) then
    raise exception 'demo seed: a city is missing (load public.cities first)';
  end if;
end $$;

-- 1. Accounts (the trigger creates the profiles)
insert into auth.users (instance_id, id, aud, role, email, email_confirmed_at, banned_until, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)
select '00000000-0000-0000-0000-000000000000', md5('bizz-demo-' || slug)::uuid, 'authenticated', 'authenticated', 'demo+' || slug || '@bizz.test', now(), '2999-01-01',
       '{"provider":"email","providers":["email"],"demo":true}', jsonb_build_object('display_name', owner_name), now() - interval '30 days', now(), '', '', '', ''
  from _demo_shops
on conflict (id) do nothing;

update public.profiles p
   set username = s.slug, display_name = s.owner_name, city_id = c.id, terms_accepted_at = coalesce(p.terms_accepted_at, now()),
       phone_verified = true, role = 'seller', active_mode = 'seller'
  from _demo_shops s join public.cities c on c.insee_code = s.insee
 where p.id = md5('bizz-demo-' || s.slug)::uuid;

-- 2. Shops (no Founder badge: it is kept for real sellers)
insert into public.shops (id, owner_id, slug, name, bio, city_id, location, instagram, created_at)
select md5('bizz-demo-shop-' || s.slug)::uuid, md5('bizz-demo-' || s.slug)::uuid, s.slug, s.name, s.bio, c.id, c.location, s.instagram, now() - interval '30 days'
  from _demo_shops s join public.cities c on c.insee_code = s.insee
on conflict (owner_id) do nothing;

-- 3. Posts: 5 per shop, spread over the last 20 days, a few reserved and sold
create temp table _demo_posts on commit drop as
select md5('bizz-demo-post-' || s.slug || '-' || u.k)::uuid as id, md5('bizz-demo-shop-' || s.slug)::uuid as shop_id, md5('bizz-demo-' || s.slug)::uuid as author_id,
       a.id as arch_id, ((s.idx - 1) * 5 + u.k)::int as n, a.type, a.title, a.descr, a.tags, a.price, cat.id as category_id, c.id as city_id, c.location
  from _demo_shops s
  cross join lateral unnest(s.arch) with ordinality as u(arch_id, k)
  join _demo_arch a on a.id = u.arch_id
  join public.categories cat on cat.slug = a.cat
  join public.cities c on c.insee_code = s.insee;

insert into public.posts (id, shop_id, author_id, type, title, description, hashtags, price_mode, price_cents, category_id, city_id, location, status, published_at, bumped_at, expires_at)
select id, shop_id, author_id, type::public.post_type, title, descr, tags,
       case when price is null then 'on_quote' else 'fixed' end::public.price_mode,
       case when price is null then null else (round(price * (0.9 + ((n * 7) % 26) / 100.0) / 50.0) * 50)::int end,
       category_id, city_id, location,
       (case when n % 15 = 7 then 'reserved' when n % 15 = 11 then 'sold' else 'available' end)::public.post_status,
       now() - make_interval(hours => (n * 37) % 480 + 1), now() - make_interval(hours => (n * 37) % 480 + 1),
       now() - make_interval(hours => (n * 37) % 480 + 1) + interval '60 days'
  from _demo_posts
on conflict (id) do nothing;

insert into public.post_media (post_id, kind, position, storage_path, width, height)
select p.id, 'image', (v - 1)::smallint,
       md5('bizz-demo-assets')::uuid || '/demo/a' || lpad(p.arch_id::text, 2, '0') || '-' || ((p.n + v) % 2 + 1) || '.jpg', 800, 1000
  from _demo_posts p cross join lateral generate_series(1, case when p.n % 3 = 0 then 2 else 1 end) v
on conflict (post_id, position) do nothing;

commit;
`;
writeFileSync(join(here, '../../supabase/seed/demo.sql'), sql);
console.log('supabase/seed/demo.sql written,', sql.length, 'bytes');
